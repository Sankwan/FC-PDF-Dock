import fitz
native = fitz.open()
p = native.new_page()
p.insert_text((55,70), 'PILOT FIELD REPORT', fontsize=22)
p.insert_textbox(fitz.Rect(55,110,550,300), 'This report contains sample documents for testing FC PDFDock.\nThe forest team checked the nursery records and prepared a field visit summary.\nThese are synthetic test records. No staff or confidential data is included.', fontsize=14)
native.save('/tmp/native.pdf')
pix = p.get_pixmap(dpi=200)
scan = fitz.open()
page = scan.new_page(width=p.rect.width, height=p.rect.height)
page.insert_image(page.rect, stream=pix.tobytes('png'))
scan.save('/tmp/scanned.pdf')
over = fitz.open()
for i in range(101): over.new_page()
over.save('/tmp/over-limit.pdf')
